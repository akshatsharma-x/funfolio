// Original 16×16 pixel-art cursor masks (R4). Used only by scripts/build-cursors.mjs — never bundled for the client.
// The build adds the outline automatically: every masked cell gets a 1-cell white ring, then a 1-cell black ring
// (= 2px each at the 32px size). Keep masks ≥ 2 cells from every edge so the outline fits.
// Chars: "." empty · "#" fill · "h" highlight · "s" shade · "k" black detail · "1" "2" "3" accents · "x" red (fixed).

import type { CursorVariant } from "./skins";

export type CursorShape = {
  rows: readonly string[];
  /** Hotspot in art cells; the build multiplies by the scale (2×/3×/4×) and floors. */
  hotspot: readonly [number, number];
};

function ring(slash: boolean): string[] {
  const rows: string[] = [];
  for (let y = 0; y < 16; y++) {
    let r = "";
    for (let x = 0; x < 16; x++) {
      const d = Math.hypot(x - 7.5, y - 7.5);
      r += d <= 5.7 && d >= 3.6 ? "#" : slash && Math.abs(x - y) <= 1 && d <= 4.4 ? "x" : ".";
    }
    rows.push(r);
  }
  return rows;
}

